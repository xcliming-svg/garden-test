import assert from 'node:assert/strict';
import {prepare} from '../simulation/io.mjs';
import {captureGeometry,runBrowser} from '../simulation/browser.mjs';
import {loadModels} from '../simulation/models.mjs';
import {createEngine} from '../simulation/engine.mjs';
import {play,profileFor} from '../simulation/agents.mjs';
const p=prepare(),measured=await captureGeometry(p),q=prepare({},measured);
assert.equal(Object.keys(measured.enemies).length,12);
assert.equal(Object.keys(measured.weapons).length,11);
const options={seed:42,dt:.05,maxSeconds:60};
const idle=profileFor('idle');
const reference=await runBrowser(p,idle,options),repeat=await runBrowser(p,idle,options);
assert.deepEqual(reference,repeat,'deterministic real scene');
const fast=play(createEngine(loadModels(q.sources,q.config),{...options,geometry:measured}),idle);
for(const k of ['result','completed','kills','spawned','shots','hits','damage','gems'])assert.equal(fast[k],reference[k],'60-second reference parity '+k);
const policy=profileFor('normal'),active=await runBrowser(p,policy,{...options,maxSeconds:120});
assert.ok(active.actions.some(a=>a.type==='DRAG_END'&&a.ok),'real scene card action');
assert.ok(active.counts.weapon_hit>0&&active.completed>=4);
console.log('PASS simulation browser',JSON.stringify({reference:reference.final,fast:fast.final,active:active.final}));
