import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const window={GardenRunRules:{survival:true}};
new Function('window','URLSearchParams',readFileSync('src/garden-economy.js','utf8'))(window,URLSearchParams);
const E=window.GardenEconomy;
assert.equal(E.enabled,true);
assert.deepEqual(E.names,['sunflower','rose','hydrangea','lavender']);
assert.deepEqual([0,2,3,5,18,21,35].map(E.indexOfCell),[0,0,1,1,2,3,3]);
for(let i=0;i<4;i++)assert.equal(
  Array.from({length:36},(_,cell)=>E.indexOfCell(cell)).filter(x=>x===i).length,9);
assert.ok(E.requiredAt(7200)>E.requiredAt(0));
assert.ok(E.requiredAt(7200)<E.tuning.growthCeiling);
const m=E.create(()=>.5),s=m.state;
assert.deepEqual(s.plots.map(p=>p.count),[0,0,0,0]);
assert.equal(s.water,0);
assert.equal(m.water(1,0),0);
assert.equal(m.gainWater(20),20);
assert.equal(m.gainWater(999),80);
assert.equal(m.gainWater(1),0);
assert.equal(s.water,100);
assert.equal(m.water(1,0),E.tuning.waterPerSecond);
assert.equal(m.stage(0),2);
assert.ok(m.water(10,0)>0);
assert.equal(s.plots[0].phase,'bloom');
assert.equal(s.plots[0].yield,5);
assert.equal(s.plots[0].flowers.length,5);
assert.equal(m.stage(0),3);
assert.equal(Array.from({length:9},(_,i)=>m.wilt(E.localCell(0,i))).filter(Boolean).length,4);
assert.ok(m.tick(1.5).includes(0));
assert.equal(s.plots[0].phase,'flight');
assert.equal(s.plots[0].count,0);
m.tick(.85);
assert.equal(s.plots[0].phase,'growing');
assert.equal(s.plots[0].count,5);
assert.equal(s.totalHarvested,5);
assert.equal(m.stage(0),1);
assert.deepEqual(s.plots.slice(1).map(p=>p.count),[0,0,0]);
const hp=s.hp;
assert.ok(m.damage(100,1)>0);
assert.ok(s.hp<hp);
assert.ok(m.heal(2)>0);
assert.ok(s.hp<=E.tuning.gardenHp);
assert.ok(s.owned.has('rock'));
assert.ok(!s.owned.has('boomerang'));
assert.deepEqual(m.bonus('rock'),{level:1,volley:1,speed:0});
for(const plot of s.plots)plot.count=100;
const before=s.plots.map(p=>p.count);
assert.ok(m.purchase('boomerang'));
assert.ok(!m.purchase('boomerang'));
assert.ok(s.plots.some((p,i)=>p.count<before[i]));
assert.ok(m.upgrade('rock','power'));
assert.ok(m.upgrade('rock','volley'));
assert.ok(m.upgrade('rock','speed'));
assert.deepEqual(m.bonus('rock'),{level:2,volley:2,speed:.15});
assert.ok(m.purchase('shield'));
assert.equal(m.defense(),6);
assert.ok(m.upgrade('shield','power'));
assert.equal(m.defense(),12);
assert.ok(m.purchase('shoe'));
assert.equal(m.speed(),48);
assert.ok(m.upgrade('shoe','power'));
assert.equal(m.speed(),54);
assert.equal(m.upgrade('rock','not-a-type'),false);
console.log('PASS: main-derived four beds, water, random yield, wilt, flight, flower purchases, upgrades and garden HP');
