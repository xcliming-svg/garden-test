import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const window={GardenRunRules:{survival:true}};
new Function('window',readFileSync('src/garden-economy.js','utf8'))(window);
const E=window.GardenEconomy;
assert.equal(E.enabled,true);
assert.deepEqual(E.names,['sunflower','rose','hydrangea','lavender']);
assert.deepEqual([44,45,54,55].map(E.indexOfCell),[0,1,2,3]);
for(let side=1;side<=5;side++){
  const cells=E.cellsForSide(side);
  assert.equal(cells.length,4*side*side);
  assert.equal(new Set(cells.map(x=>x[0])).size,cells.length);
  for(let i=0;i<4;i++)assert.equal(cells.filter(([id])=>E.indexOfCell(id)===i).length,side*side);
}
assert.deepEqual(E.cellsForSide(1),[[44,'sunflower'],[45,'rose'],[54,'hydrangea'],[55,'lavender']]);
assert.equal(E.cellsForSide(5).length,100);
assert.ok(E.requiredAt(7200,5)>E.requiredAt(0,1));
assert.ok(E.requiredAt(10800,5)<=E.tuning.growthCeiling);

const m=E.create(()=>.5),s=m.state;
assert.equal(s.side,1);
assert.equal(m.gainWater(20),20);
assert.equal(m.gainWater(999),80);
assert.equal(s.water,100);
assert.equal(m.water(1,0),E.tuning.waterPerSecond);
assert.equal(m.stage(44),2);
assert.ok(m.water(10,0)>0);
assert.equal(s.plots[0].phase,'bloom');
assert.equal(s.plots[0].yield,1,'first harvest yields exactly one flower');
assert.equal(m.wilt(44),false,'all flowers bloom and never wilt');
assert.equal(m.expand(),false,'cannot expand while a plot is harvesting');
assert.ok(m.tick(1.5).includes(0));
assert.equal(s.plots[0].phase,'flight');
assert.equal(s.plots[0].count,0);
m.tick(.85);
assert.equal(s.plots[0].phase,'growing');
assert.equal(s.plots[0].count,1);
assert.equal(s.totalHarvested,1);
assert.equal(m.stage(44),1);
assert.equal(m.available('wheel'),false,'second tier is not initially unlocked');
for(const p of s.plots)p.count=10000;
assert.equal(m.purchase('wheel'),false,'money cannot bypass garden unlock');

for(let next=2;next<=5;next++){
  const cost=m.expansionCost();
  const before=s.plots.map(p=>p.count);
  assert.ok(cost.every(c=>c===E.tuning.expansionCosts[next-2]));
  assert.ok(m.expand(),'all beds expand together');
  assert.equal(s.side,next);
  assert.ok(s.plots.every((p,i)=>p.count===before[i]-cost[i]));
  assert.equal(E.cellsForSide(next).length,4*next*next);
  assert.ok(s.plots.every(p=>p.required===E.requiredAt(s.elapsed,next)));
  assert.ok(m.available('boomerang'));
  assert.ok(m.available('wheel')===(next>=2));
  assert.ok(m.available('sprinkler')===(next>=4));
  const id=next%4;
  m.gainWater(100);
  m.water(10,id);
  assert.equal(s.plots[id].yield,next*next,'whole bed blooms with exact expanded size');
  assert.equal(s.plots[id].flowers.length,next*next);
  m.tick(1.5);m.tick(.85);
  assert.ok(s.plots[id].count>=next*next);
}
assert.equal(m.expansionCost(),null,'only four expansions allowed');
assert.equal(m.expand(),false);
assert.ok(m.purchase('boomerang'));
assert.ok(!m.purchase('boomerang'));
assert.ok(m.purchase('sprinkler'));
assert.ok(m.upgrade('rock','power'));
assert.ok(m.upgrade('rock','volley'));
assert.ok(m.upgrade('rock','speed'));
assert.deepEqual(m.bonus('rock'),{level:2,volley:2,speed:.15});
assert.ok(m.upgrade('rock','power'));
assert.equal(m.upgrade('rock','power'),false);
assert.equal(m.bonus('rock').level,3);
assert.ok(m.purchase('shield'));assert.equal(m.defense(),6);
assert.ok(m.upgrade('shield','power'));assert.equal(m.defense(),12);
assert.ok(m.purchase('shoe'));assert.equal(m.speed(),48);
assert.ok(m.upgrade('shoe','power'));assert.equal(m.speed(),54);
assert.equal(m.upgrade('rock','not-a-type'),false);
assert.ok(m.cost('rock','power')===null);
assert.ok(m.cost('rock','volley')?.reduce((a,b)=>a+b,0)>15);
const hp=s.hp;
assert.ok(m.damage(100,1)>0);
assert.ok(s.hp<hp);
assert.ok(m.heal(2)>0);
console.log('PASS: four synchronous 1→4→9→16→25 gardens, 100 cells, full bloom, expansion prices, tier locks, equipment upgrades, survival HP');
