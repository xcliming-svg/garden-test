import assert from 'node:assert/strict';
import {sourceSet} from '../simulation/io.mjs';
import {loadModels,defaults,resolveConfig} from '../simulation/models.mjs';
import {createEngine} from '../simulation/engine.mjs';
import {profileFor,play} from '../simulation/agents.mjs';
import {compact,summarize} from '../simulation/metrics.mjs';
const sources=sourceSet(),baseline=loadModels(sources),config=resolveConfig(baseline);
let checks=0;
const eq=(a,b,m)=>{checks++;assert.deepEqual(a,b,m);};
const ok=(v,m)=>{checks++;assert.ok(v,m);};
const invalid=p=>{checks++;assert.throws(()=>resolveConfig(baseline,p),/Invalid config/);};
eq(config.run.dropWeights,[.69,.1,.18,.03]);eq(config.run.costs,[40,60,85,115,150,200]);
eq(config.blueprint.length,16);eq(config.enemyHp['3_caterpillar'],10);
eq(config.weapons.rock.damage,[10,13,16]);
invalid({run:{dropWeights:[.7,.1,.2,.1]}});invalid({run:{notAField:1}});
invalid({blueprint:[[44,'daisy'],[45,'sunflower'],[54,'tulip'],[55,'hydrangea'],[0,'rose']]});
invalid({run:{maxSlots:11}});invalid({weapons:{rock:{cooldown:[0,1,1]}}});
invalid({enemyHp:{ghost:10}});invalid({enemyDamage:{ghost:10}});
invalid({waves:[[0,1,3,1,[['4_beetle',1]]]]});
invalid({weapons:{rock:{damage:[[1],2,3]}}});
const full=Array.from({length:100},(_,i)=>[i,new Map(config.initial).get(i)||baseline.GardenFlowerGrowth.names[i%6]]);
const extended=resolveConfig(baseline,{blueprint:full,run:{dropWeights:[.2,.1,.65,.05]},enemyHp:{'3_caterpillar':20},weapons:{rock:{damage:[20,23,26]}},fairy:{speed:45,maxSpeed:90}});
eq(extended.blueprint.length,100);eq(extended.enemyHp['3_caterpillar'],20);
eq(loadModels(sources,extended).GardenWeaponBalance.stats('rock').damage,20);
eq(baseline.GardenWeaponBalance.stats('rock').damage,10,'isolation');
const run=(name,seed=42,seconds=500,patch=config,trace=false)=>play(createEngine(loadModels(sources,patch),{seed,dt:.05,maxSeconds:seconds,trace}),profileFor(name));
const idle=run('idle'),normal=run('normal'),repeat=run('normal'),expert=run('expert');
eq(idle.result,'defeat');ok(idle.seconds>=270&&idle.seconds<540,'opening pressure');
eq(idle.final.flowers,0);eq(normal.result,'victory');eq(normal.completed,16);
eq(normal,repeat,'same seed, profile and settings');
eq(expert.result,'victory');ok(normal.actions.some(a=>a.type==='DRAG_END'&&a.ok),'actual action');
ok(normal.counts.weapon_hit>0);eq(normal.kills,normal.counts.drop_roll,'one roll per kill');
eq(normal.counts.card_spawn,(normal.counts.card_use||0)+(normal.counts.card_expire||0)+normal.final.cards,'card conservation');
eq(normal.spawned,normal.kills+normal.final.enemies,'enemy conservation');
eq(Object.values(normal.byWeapon).reduce((a,w)=>a+(w.damage||0),0),normal.damage,'attributed damage');
ok(normal.maxOpportunityGap>=0&&normal.maxProgressGap>=0);
const replay=createEngine(loadModels(sources,config),{seed:42,dt:.05,maxSeconds:500});
let i=0;while(!replay.finished){while(i<normal.actions.length&&normal.actions[i].t<=replay.time+1e-6){const {t,ok:accepted,reason,...action}=normal.actions[i++];eq(replay.dispatch(action),accepted,'action replay');}replay.step();}
eq(compact(replay.result()),compact(normal),'exact replay');eq(i,normal.actions.length);
const invalidActions=createEngine(loadModels(sources,config),{maxSeconds:1,dt:.05,trace:true});
eq(invalidActions.dispatch({type:'DRAG_START',cardId:123456}),false);
eq(invalidActions.dispatch({type:'BUY_SLOT'}),false);
eq(invalidActions.dispatch({type:'UPROOT_START',cell:0}),false);
const timed=run('normal',42,1);eq(timed.result,'timeout');eq(timed.seconds,1);
const large=run('expert',3,30,extended);eq(large.required,100);eq(large.result,'timeout');
const report=summarize([idle,normal,timed]);eq(report.runs,3);eq(report.wins,1);eq(report.defeats,1);eq(report.timeouts,1);eq(report.winTime.n,1);
console.log('PASS simulation model',checks,{idle:idle.seconds,normal:normal.seconds,expert:expert.seconds,large:large.completed});
